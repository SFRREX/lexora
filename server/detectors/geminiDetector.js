import { GoogleGenAI, Type } from '@google/genai';
import { BaseDetector } from './baseDetector.js';

export class GeminiDetectorAdapter extends BaseDetector {
  constructor() {
    super('gemini', 'Lexora Neural AI Detector (Gemini)');
  }

  isConfigured() {
    const key = process.env.GEMINI_API_KEY;
    return Boolean(key && key.trim() && key !== 'your_gemini_api_key_here');
  }

  getCapabilities() {
    return {
      sentenceHighlights: true,
      paragraphScores: true,
      multilingual: true,
      burstinessScore: true,
      perplexityScore: true,
      isFreeProvider: true,
      inputMinWords: 20,
      providerUrl: 'https://aistudio.google.com/',
      apiDocs: 'https://ai.google.dev/docs',
    };
  }

  normalizeDetectionResult(raw, originalText) {
    const classification = (raw.overall_classification || 'mixed').toLowerCase();
    const probabilityScore =
      typeof raw.probability_score === 'number'
        ? Math.round(raw.probability_score * 100) / 100
        : 0.5;

    const sentences = Array.isArray(raw.sentences)
      ? raw.sentences.map((s, idx) => ({
          id: `s-${idx}`,
          text: s.text || '',
          label: (s.classification || 'mixed').toLowerCase(),
          score: typeof s.score === 'number' ? Math.round(s.score * 100) / 100 : probabilityScore,
          perplexity: typeof s.perplexity === 'number' ? Math.round(s.perplexity * 10) / 10 : null,
          reason: s.reason || '',
        }))
      : this._splitFallbackSentences(originalText, classification, probabilityScore);

    const words = originalText.trim().split(/\s+/).filter(Boolean);

    return {
      providerId: this.id,
      providerName: this.name,
      classification,
      probabilityScore,
      confidence: raw.confidence_category || (probabilityScore > 0.8 || probabilityScore < 0.2 ? 'high' : 'medium'),
      burstiness: typeof raw.burstiness_score === 'number' ? Math.round(raw.burstiness_score * 10) / 10 : 38.2,
      perplexity: typeof raw.perplexity_score === 'number' ? Math.round(raw.perplexity_score * 10) / 10 : 42.1,
      sentences,
      paragraphs: [],
      scanTimestamp: new Date().toISOString(),
      modelVersion: `${raw._activeModel || 'gemini-3.5-flash'} (Forensic Stylometrics)`,
      wordCount: words.length,
      characterCount: originalText.length,
      rawSummary: {
        reasoning: raw.reasoning_summary,
      },
    };
  }

  _splitFallbackSentences(text, overallClass, score) {
    const raw = text.match(/[^.!?]+[.!?]+|[^.!?]+$/g) || [text];
    return raw.map((s, idx) => ({
      id: `s-${idx}`,
      text: s.trim(),
      label: overallClass,
      score,
      perplexity: null,
    })).filter((s) => s.text.length > 0);
  }

  async detect(text, _options = {}) {
    if (!this.isConfigured()) {
      throw new Error(
        'GEMINI_API_KEY is not configured. Please set GEMINI_API_KEY in your .env file.'
      );
    }

    const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
    const models = ['gemini-3.5-flash', 'gemini-3.5-flash-lite', 'gemini-3.8-flash'];

    const prompt = `You are an elite forensic linguist and AI-generated text detection specialist.
Analyze the following document to estimate the probability that it was generated by a Large Language Model (such as GPT-4, Gemini, Claude) versus written by a human.

EVALUATION METHODOLOGY:
1. Perplexity (predictability): AI text favors high-frequency, statistically predictable token transitions.
2. Burstiness (sentence variation): Human writing features natural fluctuations in clause length, rhythm, and syntax, whereas AI text tends to be uniformly structured.
3. Stylistic Tropes: Check for hallmarks like "delve into", "intricate tapestry", "plays a pivotal role", "underscores the importance", "in conclusion it is crucial", and decorative ungrounded signposting.
4. Specificity & Evidence: Human academic writing anchors assertions in concrete figures and causal mechanisms.

DOCUMENT TO ANALYZE:
"""
${text}
"""

Evaluate every sentence and the overall document strictly adhering to the JSON schema.`;

    let lastError = null;
    for (const model of models) {
      try {
        const response = await ai.models.generateContent({
          model,
          contents: prompt,
          config: {
            temperature: 0.1,
            responseMimeType: 'application/json',
            responseJsonSchema: {
              type: Type.OBJECT,
              properties: {
                overall_classification: {
                  type: Type.STRING,
                  description: 'Overall classification: "ai", "human", or "mixed"',
                },
                probability_score: {
                  type: Type.NUMBER,
                  description: 'Estimated AI probability between 0.0 (completely human) and 1.0 (completely AI)',
                },
                confidence_category: {
                  type: Type.STRING,
                  description: '"high", "medium", or "low"',
                },
                burstiness_score: {
                  type: Type.NUMBER,
                  description: 'Estimated sentence variance burstiness score (typically 10 to 80)',
                },
                perplexity_score: {
                  type: Type.NUMBER,
                  description: 'Estimated perplexity rating (typically 10 to 100)',
                },
                reasoning_summary: {
                  type: Type.STRING,
                  description: 'A 1-2 sentence forensic linguistic summary',
                },
                sentences: {
                  type: Type.ARRAY,
                  items: {
                    type: Type.OBJECT,
                    properties: {
                      text: { type: Type.STRING },
                      classification: { type: Type.STRING, description: '"ai", "human", or "mixed"' },
                      score: { type: Type.NUMBER, description: 'AI probability from 0.0 to 1.0' },
                      perplexity: { type: Type.NUMBER },
                      reason: { type: Type.STRING },
                    },
                    required: ['text', 'classification', 'score'],
                  },
                },
              },
              required: [
                'overall_classification',
                'probability_score',
                'confidence_category',
                'burstiness_score',
                'perplexity_score',
                'sentences',
              ],
            },
          },
        });

        if (response.text) {
          const parsed = JSON.parse(response.text);
          parsed._activeModel = model;
          return this.normalizeDetectionResult(parsed, text);
        }
      } catch (err) {
        lastError = err;
        console.warn(`Gemini detector with model ${model} failed, trying fallback:`, err.message);
      }
    }

    throw lastError || new Error('Lexora Neural AI Detector was unavailable.');
  }
}
