import { BaseDetector, classifySentenceFourTier, computeFourTierDistribution } from './baseDetector.js';
import { isCloudflareConfigured, runCloudflareWorkersAI } from '../cloudflareAiService.js';

export class CloudflareDetectorAdapter extends BaseDetector {
  constructor() {
    super('cloudflare', 'Lexora Neural AI Detector (Cloudflare Llama 3.1 70B)');
  }

  isConfigured() {
    return isCloudflareConfigured();
  }

  getCapabilities() {
    return {
      sentenceHighlights: true,
      paragraphScores: true,
      multilingual: true,
      burstinessScore: true,
      perplexityScore: true,
      isFreeProvider: true,
      inputMinWords: 20,
      providerUrl: 'https://developers.cloudflare.com/workers-ai/',
      apiDocs: 'https://developers.cloudflare.com/workers-ai/models/llama-3.1-70b-instruct/',
    };
  }

  normalizeDetectionResult(raw, originalText) {
    const classification = (raw.overall_classification || 'mixed').toLowerCase();
    const rawProb = typeof raw.probability_score === 'number' ? raw.probability_score : 0.5;
    let probabilityScore =
      rawProb > 1
        ? Math.round(rawProb) / 100
        : Math.round(rawProb * 100) / 100;

    // Harmonize score with classification if model had schema inconsistency
    if (classification === 'human' && probabilityScore > 0.35) {
      probabilityScore = Math.min(0.20, probabilityScore < 1 ? Math.round((1 - probabilityScore) * 100) / 100 : 0.15);
    } else if (classification === 'ai' && probabilityScore < 0.65) {
      probabilityScore = Math.max(0.85, probabilityScore);
    }

    const sentences = Array.isArray(raw.sentences) && raw.sentences.length > 0
      ? raw.sentences.map((s, idx) => {
          const rawSentScore = typeof s.score === 'number' ? s.score : probabilityScore;
          const score =
            rawSentScore > 1
              ? Math.round(rawSentScore) / 100
              : Math.round(rawSentScore * 100) / 100;
          const label = (s.classification || (score >= 0.65 ? 'ai' : score >= 0.35 ? 'mixed' : 'human')).toLowerCase();
          const tierInfo = classifySentenceFourTier(score, label);
          return {
            id: `s-${idx}`,
            text: s.text || '',
            label,
            score,
            perplexity: typeof s.perplexity === 'number' ? Math.round(s.perplexity * 10) / 10 : null,
            reason: s.reason || '',
            tier: tierInfo.tier,
            tierLabel: tierInfo.tierLabel,
          };
        })
      : this._splitFallbackSentences(originalText, classification, probabilityScore);

    const fourTierDistribution = computeFourTierDistribution(sentences);
    const words = originalText.trim().split(/\s+/).filter(Boolean);

    return {
      providerId: this.id,
      providerName: this.name,
      classification,
      probabilityScore,
      confidence: raw.confidence_category || (probabilityScore > 0.8 || probabilityScore < 0.2 ? 'high' : 'medium'),
      burstiness: typeof raw.burstiness_score === 'number' ? Math.round(raw.burstiness_score * 10) / 10 : 35.0,
      perplexity: typeof raw.perplexity_score === 'number' ? Math.round(raw.perplexity_score * 10) / 10 : 45.0,
      sentences,
      fourTierDistribution,
      paragraphs: [],
      scanTimestamp: new Date().toISOString(),
      modelVersion: `${raw._activeModel || '@cf/meta/llama-3.1-70b-instruct'} (Open-Weight Neural Stylometrics)`,
      wordCount: words.length,
      characterCount: originalText.length,
      rawSummary: {
        reasoning: raw.reasoning_summary,
      },
    };
  }

  _splitFallbackSentences(text, overallClass, score) {
    const raw = text.match(/[^.!?]+[.!?]+|[^.!?]+$/g) || [text];
    return raw.map((s, idx) => {
      const tierInfo = classifySentenceFourTier(score, overallClass);
      return {
        id: `s-${idx}`,
        text: s.trim(),
        label: overallClass,
        score,
        perplexity: null,
        tier: tierInfo.tier,
        tierLabel: tierInfo.tierLabel,
      };
    }).filter((s) => s.text.length > 0);
  }

  async detect(text, _options = {}) {
    if (!this.isConfigured()) {
      throw new Error(
        'Cloudflare Workers AI credentials (CLOUDFLARE_ACCOUNT_ID and CLOUDFLARE_API_TOKEN) are not configured.'
      );
    }

    const prompt = `You are an elite forensic linguist and AI-generated text detection specialist.
Analyze the following document to estimate the probability that it was generated by a Large Language Model (such as GPT-4, Llama, Claude) versus written by a human.

EVALUATION METHODOLOGY:
1. Perplexity (predictability): AI text favors high-frequency, statistically predictable token transitions.
2. Burstiness (sentence variation): Human writing features natural fluctuations in clause length, rhythm, and syntax, whereas AI text tends to be uniformly structured.
3. Stylistic Tropes: Check for hallmarks like "delve into", "intricate tapestry", "plays a pivotal role", "underscores the importance", "in conclusion it is crucial", and decorative ungrounded signposting.
4. Specificity & Evidence: Human academic writing anchors assertions in concrete figures and causal mechanisms.

DOCUMENT TO ANALYZE:
"""
${text}
"""

Respond ONLY with a valid JSON object matching this exact schema:
{
  "overall_classification": "ai" | "human" | "mixed",
  "probability_score": 0.15,
  "confidence_category": "high" | "medium" | "low",
  "burstiness_score": 32.5,
  "perplexity_score": 68.0,
  "reasoning_summary": "1-2 sentence forensic explanation"
}`;

    const systemInstruction = 'You are an AI detection forensic engine. Analyze the text objectively and return ONLY valid JSON matching the requested structure without markdown or explanation.';

    const cfResult = await runCloudflareWorkersAI(prompt, {
      systemInstruction,
      temperature: 0.1,
      model: '@cf/meta/llama-3.1-70b-instruct',
      noCache: true,
      maxTokens: 512,
    });

    if (!cfResult || !cfResult.text) {
      throw new Error('Cloudflare Workers AI returned an empty detection response.');
    }

    let parsed;
    try {
      const cleaned = cfResult.text.replace(/^```[a-zA-Z]*\n?([\s\S]*?)\n?```$/g, '$1').trim();
      parsed = JSON.parse(cleaned);
    } catch {
      // If JSON parsing fails, extract JSON block via regex
      const jsonMatch = cfResult.text.match(/\{[\s\S]*\}/);
      if (jsonMatch) {
        parsed = JSON.parse(jsonMatch[0]);
      } else {
        throw new Error('Failed to parse Cloudflare Workers AI detection JSON.');
      }
    }

    parsed._activeModel = cfResult.model;
    return this.normalizeDetectionResult(parsed, text);
  }
}
